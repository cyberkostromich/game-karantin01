#!/usr/bin/env python3
"""asset_list.py — собирает docs/06_asset_list.md из manifest.json моделей, набора иконок и списка недостающих ассетов."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "asset_gen"))
import icons  # noqa: E402

man = json.loads((ROOT / "assets" / "models" / "manifest.json").read_text())
L = []; w = L.append
w("# Список ассетов\n")
w("> Сгенерировано `tools/asset_list.py`. Статусы: ✅ есть плейсхолдер в пакете · 🎨 нужен финал · 🔊 звук · ⏳ Фаза 1+\n")

CAT_RU = {"units": "Военные", "civilians": "Мирные", "zombies": "Заражённые", "vehicles": "Техника",
          "buildings": "Постройки игрока", "city": "Город", "props": "Пропсы и ресурсные узлы", "pickups": "Лут"}
w("## 1. 3D-модели (плейсхолдеры в пакете)\n")
w(f"Всего: **{len(man)}** моделей · формат `.glb` · один материал `palette` · превью: `previews/models/`, листы: `previews/sheet_*.png`\n")
for cat, ru in CAT_RU.items():
    rows = [m for m in man if m["category"] == cat]
    if not rows:
        continue
    w(f"### {ru} ({len(rows)})\n")
    w("| Файл | Треуг. | Габарит, м (X×Y×Z) | Узлы | Статус |"); w("|---|---|---|---|---|")
    for m in rows:
        nodes = ", ".join(f"`{n}`" for n in m["nodes"])
        s = m["size_m"]
        w(f"| `{m['file']}` | {m['tris']} | {s[0]}×{s[1]}×{s[2]} | {nodes} | ✅ 🎨 |")
    w("")

w("## 2. UI-иконки\n")
w(f"Всего: **{len(icons.ICONS)}** · `assets/icons/svg/<id>.svg` (бейдж), `svg/glyph/<id>.svg` (без бейджа), `png/64`, `png/128` · лист: `previews/sheet_icons.png`\n")
w("| ID | Подпись | Категория |"); w("|---|---|---|")
for k, (cat, label, _) in icons.ICONS.items():
    w(f"| `{k}` | {label} | {cat} |")
w("")

w("## 3. Текстуры и материалы\n")
w("| Ассет | Статус | Примечание |"); w("|---|---|---|")
for a, s, n in [
    ("`assets/textures/palette.png` 256×256", "✅", "85 цветов, общая для всех моделей"),
    ("Шейдер `team_color` (замена ячейки TEAM)", "🎨", "Godot ShaderMaterial: если UV в ячейке (0,5) → albedo = team_color"),
    ("Шейдер `infection` (lerp к INFECT_GLOW + wobble)", "🎨", "Параметр 0..1 от таймера инкубации"),
    ("Шейдер окон зданий города", "🎨", "Окна процедурно по мировым координатам: полосы 2.8 м по Y, шаг 2.2 м; ночью часть светится"),
    ("Декали: кровь, воронка, кислота, сажа", "🎨", "4–6 вариантов, атлас 512×512"),
    ("Туман войны", "🎨", "Текстура видимости 4 м/пикс → шейдер террейна и зданий"),
    ("Ночное небо / skybox", "🎨", "Градиент + силуэт МГУ и Москва-Сити вдали"),
]:
    w(f"| {a} | {s} | {n} |")
w("")

w("## 4. Город\n")
w("| Ассет | Статус | Примечание |"); w("|---|---|---|")
for a, s, n in [
    ("Чанки Лужников из OSM", "🛠", "Генерирует `tools/osm_city/build_city.py` (нужен интернет для выгрузки Overpass)"),
    ("`city_test_district.glb`", "✅", "Тестовый квартал 120×120 м для прототипа до OSM"),
    ("Арена «Лужники» (чаша стадиона)", "🎨", "Кастом, ~8k треуг., один вход с юга, поле = посадка эвакуации"),
    ("Новодевичий монастырь (стены, башни, собор)", "🎨", "Кастом, узнаваемый силуэт"),
    ("Метромост + станция «Воробьёвы горы»", "🎨", "Кастом, двухуровневый"),
    ("Эстакада ТТК, мосты", "🎨", "Модульные пролёты"),
    ("Силуэт МГУ (задник)", "🎨", "Без детализации, ≤ 2k треуг."),
]:
    w(f"| {a} | {s} | {n} |")
w("")

w("## 5. Звук 🔊\n")
w("| Группа | Список |"); w("|---|---|")
for g, s in [
    ("Оружие", "АК (одиночный/очередь, с глушителем), снайперская винтовка, пистолет, автопушка БМП, танковое орудие, пулемёт, миниган вертолёта, граната, НАР"),
    ("Техника", "двигатель БМП (холостой/движение), танк (гусеницы, двигатель, поворот башни), вертолёт (ротор, приближение/удаление), удар тарана"),
    ("Зомби", "стоны ходока ×6, рычание бегуна ×4, крик крикуна ×3 (слышен издалека!), удар громилы, плевок, хлюпанье гнезда, шаги орды (луп)"),
    ("Мирные", "испуг ×4, «спасибо!» ×3 (рус.), плач ребёнка, кашель (заражён), работа: рубка, пила, молоток, лязг металла"),
    ("База", "стройка, ворота, сирена громкоговорителя, генератор (луп), прожектор щёлк, КПП сигнал «заражён»"),
    ("UI", "клик, выбор юнита (подтверждения голосом: «Есть!», «Выдвигаюсь», «Принял» ×3 на тип), алерт волны, рассвет-гонг, исследование готово, мирные спасены"),
    ("Радио", "Голосовые реплики штаба для событий дней 1/3/5/7/10/12 — сначала TTS-заглушки"),
    ("Музыка", "День: эмбиент (2 трека), сумерки: нарастание, ночь: боевой (2 трека, интенсивность по числу зомби), финал: эвакуация, победа/поражение"),
]:
    w(f"| {g} | {s} |")
w("")

w("## 6. UI-экраны 🎨\n")
w("Главное меню · Лобби (слоты 1–4, доктрины, цвет, готовность) · Загрузка (факт о районе) · HUD (см. `07_ui_hud.md`) · "
  "Пауза · Отчёт рассвета · Дерево технологий · Экран победы/поражения со счётом и медалями · Настройки (графика, звук, клавиши)\n")
(ROOT / "docs" / "06_asset_list.md").write_text("\n".join(L))
print("docs/06_asset_list.md written")
